import * as monaco from 'monaco-editor'

export interface GeneratedRegion {
  source: string
  startLine: number // 1-based, the opening marker line
  endLine: number // 1-based, the closing marker line
  text: string // inner content between the markers
}

const START = /^<!--\s*pm:([A-Za-z0-9_-]+)\s*-->$/
const END = /^<!--\s*\/pm:([A-Za-z0-9_-]+)\s*-->$/

/**
 * Find generated regions delimited by `<!-- pm:SOURCE -->` … `<!-- /pm:SOURCE -->`.
 * These are the machine-managed blocks (e.g. the task table) the Hub distinguishes.
 */
export function parseGeneratedRegions(text: string): GeneratedRegion[] {
  const lines = text.split('\n')
  const out: GeneratedRegion[] = []
  let open: { source: string; startLine: number } | null = null

  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim()
    const s = START.exec(trimmed)
    if (s) {
      open = { source: s[1], startLine: i + 1 }
      continue
    }
    const e = END.exec(trimmed)
    if (e && open && e[1] === open.source) {
      out.push({
        source: open.source,
        startLine: open.startLine,
        endLine: i + 1,
        text: lines.slice(open.startLine, i).join('\n')
      })
      open = null
    }
  }
  return out
}

/** A stable signature of a document's generated content, for change detection. */
export function regionsSignature(regions: GeneratedRegion[]): string {
  return regions.map((r) => `${r.source}\u0000${r.text}`).join('\u0001')
}

// model URI -> regions, read by the shared hover provider.
const registry = new Map<string, GeneratedRegion[]>()
let hoverRegistered = false

export function setModelRegions(uri: string, regions: GeneratedRegion[]): void {
  registry.set(uri, regions)
}

export function clearModelRegions(uri: string): void {
  registry.delete(uri)
}

/** Register a single markdown hover provider that warns inside generated regions. */
export function ensureGeneratedHover(): void {
  if (hoverRegistered) return
  hoverRegistered = true
  monaco.languages.registerHoverProvider('markdown', {
    provideHover(model, position) {
      const regions = registry.get(model.uri.toString())
      if (!regions) return null
      const region = regions.find(
        (r) => position.lineNumber >= r.startLine && position.lineNumber <= r.endLine
      )
      if (!region) return null
      return {
        contents: [
          {
            value: `⚠ **Warning:** this section is generated by \`pm:${region.source}\`. Modifying it might cause problems!`
          }
        ]
      }
    }
  })
}
